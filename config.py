"""
App configuration.

Everything secret (SECRET_KEY, DATABASE_URL, CLOUDINARY_URL) is read from
environment variables. Locally those come from the .env file (loaded in
app/__init__.py via config.py). On Render they are set in the dashboard.

Two config classes (Step 6 Part 4):
    DevelopmentConfig — local work: debug on, SQLite fallback allowed.
    ProductionConfig  — Render: debug off, SECRET_KEY REQUIRED, secure
                        cookies, HTTPS preferred.

NEVER hardcode secrets in this file or any other file in the project.
"""

import os

# Load the .env file if it exists (local development).
# python-dotenv ignores the error if the file is missing (e.g. on Render).
try:
    from dotenv import load_dotenv
    load_dotenv()
except ImportError:
    pass


def _read_database_url():
    """DATABASE_URL from the environment, normalised for SQLAlchemy.

    Neon / Render sometimes hand out the OLD "postgres://" scheme.
    SQLAlchemy 2.x only accepts "postgresql://" — passing the old scheme
    makes the app crash at startup (this is what killed the first Render
    deploy). Convert it automatically so any Postgres URL just works.
    """
    url = os.environ.get("DATABASE_URL", "") or ""
    if url.startswith("postgres://"):
        url = "postgresql://" + url[len("postgres://"):]
    if not url:
        # Local dev fallback: a single SQLite file in instance/.
        # NOT for production — production must always set DATABASE_URL.
        url = "sqlite:///veloura.db"
    return url


class Config:
    """Base config shared by every environment."""

    # Flask needs a secret key to sign session cookies.
    # Development falls back to a fixed string so the app still starts
    # if you forget .env. Production validation (in create_app) REQUIRES
    # the real env var and refuses to start without it.
    SECRET_KEY = os.environ.get("SECRET_KEY") or "dev-only-insecure-secret-key"

    # Database URL (see _read_database_url for the postgres:// fix).
    SQLALCHEMY_DATABASE_URI = _read_database_url()

    # Silences a SQLAlchemy warning we don't need. Standard setting for Flask apps.
    SQLALCHEMY_TRACK_MODIFICATIONS = False

    # Cart / checkout shipping rules (Step 4 Feature 3).
    # Shipping costs this much below the threshold, and is free at/above it.
    SHIPPING_FEE = float(os.environ.get("SHIPPING_FEE", "99"))
    FREE_SHIPPING_ABOVE = float(os.environ.get("FREE_SHIPPING_ABOVE", "1999"))

    # Session cookie hardening — the same in every environment except
    # SESSION_COOKIE_SECURE (HTTPS-only), which is production-only below.
    SESSION_COOKIE_HTTPONLY = True
    SESSION_COOKIE_SAMESITE = "Lax"


class DevelopmentConfig(Config):
    """Settings used when FLASK_ENV=development (default locally)."""

    DEBUG = True


class ProductionConfig(Config):
    """Settings used when FLASK_ENV=production (on Render)."""

    DEBUG = False

    # Cookies only travel over HTTPS — never send the session over http.
    SESSION_COOKIE_SECURE = True

    # Links generated by url_for(..., _external=True) should be https.
    PREFERRED_URL_SCHEME = "https"

    # Signals create_app to enable the HTTPS redirect + ProxyFix.
    ENFORCE_HTTPS = True


# Map the FLASK_ENV value to the right config class.
CONFIG_MAP = {
    "development": DevelopmentConfig,
    "production": ProductionConfig,
}


def get_config():
    """Return the config class matching the current FLASK_ENV."""
    env = os.environ.get("FLASK_ENV", "development")
    return CONFIG_MAP.get(env, DevelopmentConfig)
